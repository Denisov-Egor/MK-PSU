-- 1. Удаляем старую базу, если есть (чтобы начать с чистого листа)
DROP DATABASE IF EXISTS `Выпускники учебного заведения`;

-- 2. Создаём новую базу
CREATE DATABASE `Выпускники учебного заведения`;
USE `Выпускники учебного заведения`;

-- 3. Таблица "Учебное заведение"
CREATE TABLE `Учебное заведение` (
    `Код_учебного заведения` INT NOT NULL AUTO_INCREMENT,
    `Наименование` VARCHAR(255) NOT NULL,
    `Направление учебного заведения` VARCHAR(255),
    `Дата поступления` DATE,
    PRIMARY KEY (`Код_учебного заведения`)
);

-- 4. Таблица "Трудоустройство"
CREATE TABLE `Трудоустройство` (
    `Код_организации` INT NOT NULL AUTO_INCREMENT,
    `Наименование` VARCHAR(255) NOT NULL,
    `Должность` VARCHAR(255),
    `Дата` DATE,
    `Контактная информация` TEXT,
    PRIMARY KEY (`Код_организации`)
);

-- 5. Таблица "Выпускник" (без DEFAULT, без лишних связей)
CREATE TABLE `Выпускник` (
    `Код_выпускника` INT NOT NULL AUTO_INCREMENT,
    `ФИО` VARCHAR(255) NOT NULL,
    `Год поступления` INT,
    `Год выпуска` INT,
    `Код_учебного заведения` INT NULL,   -- внешний ключ, NULL допустим
    `Код_организации` INT NULL,          -- внешний ключ, NULL допустим
    `Адрес` VARCHAR(255),
    `Телефон` VARCHAR(45),
    PRIMARY KEY (`Код_выпускника`),
    FOREIGN KEY (`Код_учебного заведения`)
        REFERENCES `Учебное заведение` (`Код_учебного заведения`)
        ON DELETE SET NULL,
    FOREIGN KEY (`Код_организации`)
        REFERENCES `Трудоустройство` (`Код_организации`)
        ON DELETE SET NULL
);

-- 6. Таблица "ЦТ" (централизованное тестирование)
CREATE TABLE `ЦТ` (
    `Код_записи` INT NOT NULL AUTO_INCREMENT,
    `Код_выпускника` INT NOT NULL,
    `Название предмета` VARCHAR(255) NOT NULL,
    `Баллы` INT,
    `Преподаватель` VARCHAR(255),
    PRIMARY KEY (`Код_записи`),
    FOREIGN KEY (`Код_выпускника`)
        REFERENCES `Выпускник` (`Код_выпускника`)
        ON DELETE CASCADE
);

